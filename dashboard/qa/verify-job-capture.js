async page => {
  const results = [], errors = [];
  const assert = (value, message) => { if (!value) throw new Error(message); results.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  const extractor = '../offertrack-extension/extractor.js';
  const read = async html => {
    if (html) await page.setContent(html);
    await page.addScriptTag({ path: extractor });
    return page.evaluate(() => extractOfferTrackJob(false));
  };
  await page.goto('http://localhost:8420/qa/job-capture-demo.html');
  const packet = await read();
  assert(packet.job.company === '星河研究院（虚构示例）' && packet.job.role === '数据分析师' && packet.job.city === '杭州', 'JobPosting 准确提取公司、岗位和地点');
  assert(packet.job.jd.includes('SQL') && !packet.job.jd.includes('<p>'), '保留 JD 原文并去除 HTML 标签');
  assert(packet.job.majors.includes('统计学') && packet.job.deadline === '2026-10-31', '招聘专业和截止日期提取正确');
  const domPacket = await read('<html><head><title>材料研发工程师 | 青山科技校园招聘</title></head><body><main><h1>材料研发工程师</h1><p>公司名称：青山科技</p><p>工作地点：苏州</p><p>截止日期：2026年11月5日</p><section class="job-description"><h2>岗位职责</h2><p>参与新材料性能测试。</p><h2>任职要求</h2><p>化学、材料等相关专业，本科及以上学历。</p></section></main><aside>推荐职位：销售经理，工作地点：北京</aside></body></html>');
  assert(domPacket.job.company === '青山科技' && domPacket.job.city === '苏州' && domPacket.job.role === '材料研发工程师', '无结构化信息时按中文字段识别');
  assert(domPacket.job.majors.includes('化学') && domPacket.job.deadline === '2026-11-05', '专业要求原句与中文截止日期可识别');
  assert(!domPacket.job.jd.includes('销售经理'), '职位正文不混入侧边推荐岗位');
  const selection = await page.evaluate(() => { const range = document.createRange(); range.selectNodeContents(document.querySelector('.job-description')); const selected = getSelection(); selected.removeAllRanges(); selected.addRange(range); return extractOfferTrackJob(true); });
  assert(selection.job.jd.includes('性能测试') && !selection.job.jd.includes('北京') && !selection.job.company, '选中文字模式仅使用选中内容，不挪用其他岗位公司');
  const missing = await read('<html><head><title>网站首页</title></head><body><p>欢迎浏览我们的招聘网站</p></body></html>');
  assert(!missing.job.company && !missing.job.city && !missing.job.role && !missing.job.jd && missing.warnings.length >= 5, '未识别字段留空并提示，不编造岗位');
  const multi = await read('<html><body><h1>全部岗位</h1><script type="application/ld+json">[{"@type":"JobPosting","title":"岗位甲","hiringOrganization":{"name":"甲公司"}},{"@type":"JobPosting","title":"岗位乙","hiringOrganization":{"name":"乙公司"}}]</script></body></html>');
  assert(!multi.job.company && multi.warnings.some(x => x.includes('多个岗位')), '多个 JobPosting 不任意选择一家公司的数据');
  await page.goto('http://localhost:8420/dashboard.html');
  await page.evaluate(() => localStorage.removeItem('jobhuntbot.offertrack.v1'));
  await page.reload();
  const count = async id => (await page.locator('#' + id).textContent()).trim();
  const goImport = async data => page.goto('http://localhost:8420/dashboard.html#offertrack-import=' + encodeURIComponent(JSON.stringify(data)));
  await goImport(packet);
  assert(await page.locator('#record-dialog').isVisible() && await page.locator('#field-role').inputValue() === packet.job.role, '插件导入链接自动打开并填入新增表单');
  assert(await page.locator('#field-jd').inputValue() === packet.job.jd && await page.locator('#field-majors').inputValue() === packet.job.majors, 'JD 与招聘专业逐字进入对应字段');
  assert(await page.locator('#field-stage').inputValue() === 'planned' && !(await page.locator('#field-date').inputValue()) && !(await page.locator('#field-event-at').inputValue()), '未投递的收藏不会伪造投递日期或面试安排');
  assert(await count('stat-total') === '8' && !page.url().includes('offertrack-import'), '预填不自动保存，并清理地址中的导入内容');
  await page.locator('#record-form button[type="submit"]').click();
  assert(await count('tab-planned') === '1' && await count('stat-total') === '8' && await count('stat-active') === '6' && await count('stat-week') === '4', '保存待投递岗位，不增加已投递、进行中及安排统计');
  await page.reload();
  await page.locator('#search').fill('统计学');
  assert(await page.locator('#jobs-body [data-edit]').count() === 1, '保存后刷新保留新字段，可按招聘专业搜索');
  await page.locator('#jobs-body [data-edit]').click();
  assert(await page.locator('#field-jd').inputValue() === packet.job.jd, '重新编辑时 JD 完整保留');
  await page.locator('#field-stage').selectOption('applied');
  assert(!!await page.locator('#field-date').inputValue(), '实际投递后切换阶段提供可修改的当天日期');
  await page.locator('#record-form button[type="submit"]').click();
  assert(await count('stat-total') === '9' && await count('stat-active') === '7', '确认已投递后才更新投递和流程统计');
  await goImport({ ...packet, job: { ...packet.job, sourceUrl: packet.job.sourceUrl + '?utm_source=test' } });
  assert(await page.locator('#job-duplicate').isVisible(), '同一岗位含跟踪参数的链接仍提示重复');
  await page.locator('#record-form button[type="submit"]').click();
  assert(await page.locator('#form-error').isVisible() && await count('tab-all') === '9', '未明确确认时拦截重复新增');
  await page.locator('#open-existing').click();
  assert(await page.locator('#record-title').textContent() === '编辑投递' && await page.locator('#field-stage').inputValue() === 'applied', '重复岗位可直接打开已有记录且保留实际进度');
  await page.locator('#record-dialog [data-close]').last().click();
  const bad = { ...packet, job: { ...packet.job, sourceUrl: 'javascript:alert(1)' } };
  await goImport(bad);
  assert(!(await page.locator('#record-dialog').isVisible()) && await count('tab-all') === '9', '拒绝可执行来源链接，已有数据不变');
  const exported = await page.evaluate(() => localStorage.getItem('jobhuntbot.offertrack.v1'));
  assert(JSON.parse(exported).records.some(r => r.jd === packet.job.jd && r.majors === packet.job.majors), '备份数据结构完整包含 JD 和专业');
  await page.locator('#import-job-file').setInputFiles('qa/job-import-fixture.json');
  assert(await page.locator('#field-company').inputValue() === '青山科技', '下载的单岗位 JSON 可导入表单');
  await page.setViewportSize({ width: 390, height: 844 });
  const layout = await page.locator('#record-form button[type="submit"]').boundingBox();
  assert(layout && layout.y >= 0 && layout.y + layout.height <= 844, '手机布局保存按钮保持可见');
  await page.screenshot({ path: 'qa/job-import-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'qa/job-import-desktop.png' });
  await page.locator('#record-dialog [data-close]').last().click();
  assert(!errors.length, '全流程无浏览器脚本异常');
  return { passed: results.length, results };
}
